SELECT
    A.ID AS ID,
    CASE
        WHEN B.CHILD_COUNT IS NULL THEN 0
        ELSE B.CHILD_COUNT
    END AS CHILD_COUNT
FROM ECOLI_DATA A LEFT JOIN 
(
    SELECT
    PARENT_ID AS ID,
    COUNT(*) AS CHILD_COUNT
    FROM ECOLI_DATA 
    WHERE PARENT_ID IS NOT NULL
    GROUP BY PARENT_ID
) B ON A.ID = B.ID
ORDER BY ID ASC
