SELECT
    A.USER_ID,
    A.NICKNAME,
    SUM(B.PRICE) AS TOTAL_SALES
FROM 
    USED_GOODS_USER A
JOIN (
        SELECT WRITER_ID, PRICE
        FROM USED_GOODS_BOARD 
        WHERE STATUS = 'DONE'
    ) B
ON A.USER_ID = B.WRITER_ID
GROUP BY A.USER_ID
HAVING SUM(B.PRICE) >= 700000
ORDER BY TOTAL_SALES ASC
