SELECT DISTINCT A.CAR_ID
FROM
    (
        SELECT CAR_ID
        FROM CAR_RENTAL_COMPANY_CAR
        WHERE CAR_TYPE = '세단'
    ) A,
    (
        SELECT CAR_ID
        FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY
        WHERE START_DATE >= '20221001' AND START_DATE < '20221101'
    ) B
WHERE A.CAR_ID = B.CAR_ID 
ORDER BY A.CAR_ID DESC

        

